#!/usr/bin/env python3
"""Stage a self-contained archiso profile for the SunshineOS rebuild.

The checked-in profile stays small: this script copies the verified evolution
engine and the live maintenance toolkit into airootfs, generates command
wrappers, writes build metadata, and validates the result before mkarchiso runs.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

SUBCOMMANDS = ("health", "sanity", "update", "upgrade", "migrate", "repair", "report")
IGNORED = {".git", "__pycache__", "target", ".pytest_cache", "*.pyc", ".mypy_cache"}
WRAPPER = """#!/bin/sh
# SunshineOS live command wrapper (generated by stage_profile.py).
set -eu
exec /usr/bin/python3 /usr/local/lib/sunshine/sunshine_live.py {command} "$@"
"""
DISPATCHER = """#!/bin/sh
# SunshineOS live maintenance dispatcher (generated by stage_profile.py).
set -eu
exec /usr/bin/python3 /usr/local/lib/sunshine/sunshine_live.py "$@"
"""
DOC_FILES = ("README.md",)


def ignore_parts(path: str, names: list[str]) -> set[str]:
    return {name for name in names if name in IGNORED or name.endswith(".pyc")}


def copy_tree(src: Path, dst: Path) -> None:
    if not src.is_dir():
        raise FileNotFoundError(f"missing source directory: {src}")
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(src, dst, ignore=ignore_parts, symlinks=True)


def stage(repo: Path, profile_src: Path, staged: Path, *, build_id: str = "") -> dict[str, object]:
    repo = repo.resolve()
    profile_src = profile_src.resolve()
    if not (profile_src / "profiledef.sh").is_file():
        raise FileNotFoundError(f"profile is missing profiledef.sh: {profile_src}")

    if staged.exists():
        shutil.rmtree(staged)
    staged.mkdir(parents=True)
    shutil.copytree(profile_src, staged, dirs_exist_ok=True, symlinks=True)

    airootfs = staged / "airootfs"
    engine_dst = airootfs / "opt" / "sunshine" / "evolution-engine"
    lib_dst = airootfs / "usr" / "local" / "lib" / "sunshine"
    bin_dst = airootfs / "usr" / "local" / "bin"
    doc_dst = airootfs / "usr" / "share" / "doc" / "sunshine"
    for directory in (engine_dst, lib_dst, bin_dst, doc_dst):
        directory.mkdir(parents=True, exist_ok=True)

    copy_tree(repo / "evolution-engine", engine_dst)
    copy_tree(repo / "iso" / "tools", lib_dst)

    for command in SUBCOMMANDS:
        path = bin_dst / f"sunshine-{command}"
        path.write_text(WRAPPER.format(command=command), encoding="utf-8")
        path.chmod(0o755)
    dispatcher = bin_dst / "sunshine-live"
    dispatcher.write_text(DISPATCHER, encoding="utf-8")
    dispatcher.chmod(0o755)

    for name in DOC_FILES:
        source = repo / "iso" / name
        if source.is_file():
            shutil.copy2(source, doc_dst / name)

    try:
        head = subprocess.run(["git", "-C", str(repo), "rev-parse", "HEAD"],
                              capture_output=True, text=True, check=False).stdout.strip()
    except OSError:
        head = ""
    metadata = {
        "build_id": build_id or dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ"),
        "generated": dt.datetime.now(dt.timezone.utc).isoformat(),
        "source_commit": head,
        "profile": str(profile_src.relative_to(repo)) if profile_src.is_relative_to(repo) else str(profile_src),
        "engine": "/opt/sunshine/evolution-engine",
        "commands": [f"sunshine-{name}" for name in SUBCOMMANDS],
    }
    info = airootfs / "usr" / "share" / "sunshine" / "BUILD_INFO.json"
    info.parent.mkdir(parents=True, exist_ok=True)
    info.write_text(json.dumps(metadata, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (airootfs / "etc" / "sunshine").mkdir(parents=True, exist_ok=True)
    (airootfs / "etc" / "sunshine" / "build-id").write_text(metadata["build_id"] + "\n", encoding="utf-8")

    validation = validate(staged)
    return {"staged": str(staged), "metadata": metadata, "validation": validation}


def validate(staged: Path) -> dict[str, object]:
    required = [
        staged / "profiledef.sh",
        staged / "packages.x86_64",
        staged / "pacman.conf",
        staged / "airootfs" / "usr" / "share" / "sunshine" / "BUILD_INFO.json",
        staged / "airootfs" / "opt" / "sunshine" / "evolution-engine" / "src" / "engine.py",
        staged / "airootfs" / "usr" / "local" / "lib" / "sunshine" / "sunshine_live.py",
    ]
    missing = [str(path.relative_to(staged)) for path in required if not path.is_file()]
    for command in SUBCOMMANDS:
        wrapper = staged / "airootfs" / "usr" / "local" / "bin" / f"sunshine-{command}"
        if not wrapper.is_file() or not os.access(wrapper, os.X_OK):
            missing.append(str(wrapper.relative_to(staged)))

    syntax: dict[str, str] = {}
    for shell_file in ("profiledef.sh",):
        path = staged / shell_file
        if path.is_file() and shutil.which("bash") is not None:
            proc = subprocess.run(["bash", "-n", str(path)], capture_output=True, text=True, check=False)
            syntax[shell_file] = "ok" if proc.returncode == 0 else proc.stderr.strip()
    return {"ok": not missing and all(value == "ok" for value in syntax.values()),
            "missing": missing, "syntax": syntax}


def main(argv: list[str] | None = None) -> int:
    here = Path(__file__).resolve().parent
    default_repo = here.parent.parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=default_repo)
    parser.add_argument("--profile", type=Path, default=None)
    parser.add_argument("--staged", type=Path, default=None)
    parser.add_argument("--build-id", default="")
    args = parser.parse_args(argv)

    repo = args.repo.resolve()
    profile = (args.profile or repo / "iso" / "profile" / "sunshine").resolve()
    staged = (args.staged or repo / "iso" / ".staged-profile").resolve()
    result = stage(repo, profile, staged, build_id=args.build_id)
    print(json.dumps(result, indent=2, sort_keys=True))
    return 0 if result["validation"]["ok"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
